def _with_input_preservation(expression: str) -> str:
    """Make mutable literal examples also assert their full nested input contract.

    Snapshot text is captured BEFORE the call, so aliasing cannot update expected
    values along with an accidentally mutated input. Arguments remain explicit
    (no star-unpacking) for the bank's signature validator.
    """
    class PreserveInputs(ast.NodeTransformer):
        counter = 0

        def visit_Call(self, node: ast.Call) -> ast.expr:
            if not isinstance(node.func, ast.Name) or node.func.id != "__FN__":
                return self.generic_visit(node)
            mutable = [i for i, arg in enumerate(node.args) if isinstance(arg, ast.List)]
            if not mutable:
                return node
            self.counter += 1
            prefix = f"_bridge_{self.counter}"
            names = [f"{prefix}_arg_{i}" for i in range(len(node.args))]
            assignments = [f"({name} := {ast.unparse(arg)})" for name, arg in zip(names, node.args)]
            snapshot = "(" + ", ".join(names[i] for i in mutable) + ",)"
            assignments += [
                f"({prefix}_before := repr({snapshot}))",
                f"({prefix}_result := __FN__({', '.join(names)}))",
                f"({prefix}_result if repr({snapshot}) == {prefix}_before else object())",
            ]
            return ast.parse("(" + ", ".join(assignments) + ")[-1]", mode="eval").body

    return ast.unparse(PreserveInputs().visit(ast.parse(expression, mode="eval")))


